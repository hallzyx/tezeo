#!/usr/bin/env node
/**
 * Copy the blockchain / coin logos we use out of @web3icons/core (MIT) into public/icons,
 * and generate src/lib/icons.generated.ts listing what is available.
 *   npm run icons:sync
 * Only the icons below are vendored (not the whole 18 MB library). Add a slug/symbol here to ship more.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = "node_modules/@web3icons/core/dist/svgs";

// Aurora's chain slug -> web3icons network file. (Simulator slugs are aliased in src/lib/icons.ts.)
const NETWORKS = {
  eth: "ethereum", base: "base", arb: "arbitrum-one", op: "optimism", pol: "polygon", bsc: "binance-smart-chain",
  avax: "avalanche", near: "near-protocol", sui: "sui", ton: "ton", tron: "tron", aptos: "aptos", stellar: "stellar",
  monad: "monad", xlayer: "x-layer", gnosis: "gnosis", scroll: "scroll", bera: "berachain", plasma: "plasma",
  btc: "bitcoin", sol: "solana", cardano: "cardano", ltc: "litecoin", xrp: "xrp", starknet: "starknet",
  abs: "abstract", movement: "movement", hood: "robinhood", aurora: "aurora",
};
// Chains without their own network logo: show the logo of their native coin instead.
const NETWORK_FROM_COIN = { doge: "DOGE", zec: "ZEC", bch: "BCH", dash: "DASH", hypercore: "HYPE" };

const COINS = ["USDC", "USDT", "DAI", "ETH", "WETH", "BTC", "WBTC", "CBBTC", "SOL", "BNB", "POL", "MATIC", "AVAX", "NEAR",
  "SUI", "TON", "TRX", "APT", "XLM", "ARB", "OP", "PYUSD", "USDE", "LINK", "UNI", "AAVE", "PEPE", "SHIB", "DOGE", "XRP",
  "ZEC", "LTC", "BCH", "DASH", "HYPE", "BERA", "MON", "XDAI", "USD1", "FDUSD", "JUP", "RAY", "PYTH", "WLD", "ENA"];

const load = async (file) => {
  if (!fs.existsSync(file)) return null;
  return (await import(pathToFileURL(path.resolve(file)).href)).default;
};
const clean = (svg) => svg.replace(/\sclass="web3icons"/, "").trim() + "\n";

fs.rmSync("public/icons", { recursive: true, force: true });
fs.mkdirSync("public/icons/chains", { recursive: true });
fs.mkdirSync("public/icons/coins", { recursive: true });

const chains = [], coins = [], missing = [];
const coinSvg = async (sym) => load(`${ROOT}/tokens/branded/${sym}.svg.js`);

for (const [slug, name] of Object.entries(NETWORKS)) {
  const svg = await load(`${ROOT}/networks/branded/${name}.svg.js`);
  if (svg) { fs.writeFileSync(`public/icons/chains/${slug}.svg`, clean(svg)); chains.push(slug); } else missing.push(`chain:${slug}`);
}
for (const [slug, sym] of Object.entries(NETWORK_FROM_COIN)) {
  const svg = await coinSvg(sym);
  if (svg) { fs.writeFileSync(`public/icons/chains/${slug}.svg`, clean(svg)); chains.push(slug); } else missing.push(`chain:${slug}`);
}
for (const sym of COINS) {
  const svg = await coinSvg(sym);
  if (svg) { fs.writeFileSync(`public/icons/coins/${sym.toLowerCase()}.svg`, clean(svg)); coins.push(sym.toLowerCase()); } else missing.push(`coin:${sym}`);
}

fs.writeFileSync("public/icons/LICENSE.txt",
`Chain and coin logos in this folder come from Web3Icons (@web3icons/core), https://github.com/0xa3k5/web3icons,
distributed under the MIT License. The logos themselves are trademarks of their respective owners and are shown
only to identify the network or coin a fan can pay with.
`);
fs.writeFileSync("src/lib/icons.generated.ts",
`// GENERATED by scripts/sync-icons.mjs. Do not edit by hand.
export const CHAIN_ICONS: ReadonlySet<string> = new Set(${JSON.stringify(chains)});
export const COIN_ICONS: ReadonlySet<string> = new Set(${JSON.stringify(coins)});
`);
const kb = (d) => Math.round(fs.readdirSync(d).reduce((s, f) => s + fs.statSync(path.join(d, f)).size, 0) / 1024);
console.log(`chains ${chains.length} (${kb("public/icons/chains")} KB), coins ${coins.length} (${kb("public/icons/coins")} KB)`);
if (missing.length) console.log("no icon available for:", missing.join(", "));
