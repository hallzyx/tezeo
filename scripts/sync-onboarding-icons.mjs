// Pulls the icons the onboarding prototype uses that the shared sprites lack -> src/components/sprite-onboarding.ts
import fs from "node:fs";
const html = fs.readFileSync("design/onboarding.html", "utf8");
const have = new Set([...(fs.readFileSync("src/components/sprite.ts", "utf8") + fs.readFileSync("src/components/sprite-landing.ts", "utf8")).matchAll(/symbol id="([^"]+)"/g)].map((m) => m[1]));
const extra = [...html.matchAll(/<symbol id="(i-[^"]+)"[\s\S]*?<\/symbol>/g)].filter((m) => !have.has(m[1])).map((m) => m[0]);
fs.writeFileSync("src/components/sprite-onboarding.ts", `// Generated by scripts/sync-onboarding-icons.mjs from design/onboarding.html. Do not edit.\nexport const SPRITE_ONBOARDING = ${JSON.stringify(extra.join(""))};\n`);
console.log("icons:", extra.length);
