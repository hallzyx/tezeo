#!/usr/bin/env node
/**
 * Sync the designer's static landing prototype into the Next.js app.
 *   design/landing.html -> src/app/_landing/markup.ts   (body markup, no scripts, no icon sprite)
 *   design/landing.css  -> src/styles/landing.css
 *   icons missing from the base sprite -> src/components/sprite-landing.ts
 * Re-run after the design changes:  npm run landing:sync
 * Behaviour (theme toggle, menu, scroll reveal, decorative QR) lives in src/app/_landing/LandingEffects.tsx.
 */
import fs from "node:fs";

const html = fs.readFileSync("design/landing.html", "utf8");
let body = html.slice(html.indexOf("<body"), html.lastIndexOf("</body>"));
body = body.slice(body.indexOf(">") + 1);

// 1) icon sprite: keep only symbols the shared sprite doesn't already define
const spriteMatch = body.match(/<svg[^>]*\swidth="0"[^>]*>[\s\S]*?<\/svg>/);
if (!spriteMatch) throw new Error("landing sprite not found");
body = body.replace(spriteMatch[0], "");
const base = fs.readFileSync("src/components/sprite.ts", "utf8");
const extra = [...spriteMatch[0].matchAll(/<symbol id="([^"]+)"[\s\S]*?<\/symbol>/g)]
  .filter((m) => !base.includes(`id="${m[1]}"`)).map((m) => m[0]);
fs.writeFileSync("src/components/sprite-landing.ts",
  "/** Extra icons used only by the landing page (generated by scripts/sync-landing.mjs). */\n" +
  `export const SPRITE_LANDING = \`${extra.join("\n")}\`;\n`);

// 2) drop the prototype's inline scripts (re-implemented in LandingEffects.tsx)
body = body.replace(/<script[\s\S]*?<\/script>/g, "").trim();

// 3) swap the prototype's text glyphs ("ETH", "B", "₮"...) for the real chain / coin logos (npm run icons:sync)
const has = (kind, slug) => fs.existsSync(`public/icons/${kind}/${slug}.svg`);
const CHAIN_BY_LABEL = { ethereum: "eth", eth: "eth", base: "base", arbitrum: "arb", arb: "arb", optimism: "op", polygon: "pol",
  "bnb chain": "bsc", avalanche: "avax", near: "near", bitcoin: "btc", btc: "btc", sui: "sui", ton: "ton", tron: "tron",
  aptos: "aptos", stellar: "stellar", monad: "monad", "x layer": "xlayer", gnosis: "gnosis", solana: "sol" };
const chainSrc = (label) => { const s = CHAIN_BY_LABEL[label.trim().toLowerCase()]; return s && has("chains", s) ? `/icons/chains/${s}.svg` : null; };
const coinSrc = (label) => { const s = label.trim().toLowerCase(); return has("coins", s) ? `/icons/coins/${s}.svg` : has("chains", s) ? `/icons/chains/${s}.svg` : null; };
const darkSet = new Set([...fs.readFileSync("src/lib/icons.generated.ts", "utf8").matchAll(/"((?:chains|coins)\/[a-z0-9-]+)"/g)].map((m) => m[1]));
const isDarkSrc = (src) => darkSet.has(src.replace(/^\/icons\//, "").replace(/\.svg$/, ""));
const cls = (src) => (isDarkSrc(src) ? ' class="tz-logo--dark"' : "");
const img = (src, px) => `<img src="${src}"${cls(src)} alt="" width="${px}" height="${px}" loading="lazy" decoding="async">`;
let swapped = 0;
// marquee chips (networks and coins)
body = body.replace(/<li class="(tzl-chain(?: tzl-chain--coin)?)"><span class="(tzl-chain__g[^"]*)" style="([^"]*)">([^<]*)<\/span>([^<]*)<\/li>/g,
  (m, li, g, style, glyph, label) => {
    const src = li.includes("--coin") ? coinSrc(label) : chainSrc(label);
    if (!src) return m;
    swapped++;
    return `<li class="${li}"><span class="${g} tzl-chain__g--img" style="${style}">${img(src, 36)}</span>${label}</li>`;
  });
// chips inside the mock "Where's your money?" screen
body = body.replace(/<span class="tz-chip__coin">([^<]*)<\/span>([^<]*)/g, (m, glyph, label) => {
  const src = chainSrc(label); if (!src) return m; swapped++;
  return `<span class="tz-chip__coin tz-chip__coin--img">${img(src, 28)}</span>${label}`;
});
// hero thread pills (SVG): <circle fill=.../><text class="g">GLYPH</text><text>LABEL</text>
body = body.replace(/<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)" fill="#[0-9A-Fa-f]+"\/><text class="g"[^>]*>[^<]*<\/text>(<text[^>]*>([^<]*)<\/text>)/g,
  (m, cx, cy, r, labelEl, label) => {
    const src = chainSrc(label); if (!src) return m; swapped++;
    const d = (+r * 2).toFixed(2);
    return `<image href="${src}"${cls(src)} x="${(+cx - +r).toFixed(2)}" y="${(+cy - +r).toFixed(2)}" width="${d}" height="${d}"/>${labelEl}`;
  });

// "Built with Solana and Aurora Intents": swap the placeholder shapes for the real logos
body = body.replace(/<span class="tzl-builder__g" style="[^"]*" aria-hidden="true"><svg[\s\S]*?<\/svg><\/span>(<b>(Solana|Aurora Intents)<\/b>)/g,
  (m, bTag, who) => {
    const slug = who === "Solana" ? "sol" : "aurora";
    if (!has("chains", slug)) return m; swapped++;
    return `<span class="tzl-builder__g tzl-builder__g--img" aria-hidden="true">${img(`/icons/chains/${slug}.svg`, 32)}</span>${bTag}`;
  });

const esc = body.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
fs.writeFileSync("src/app/_landing/markup.ts",
  "// GENERATED by scripts/sync-landing.mjs from design/landing.html. Do not edit by hand.\n" +
  `export const LANDING_HTML = \`${esc}\`;\n`);

fs.copyFileSync("design/landing.css", "src/styles/landing.css");
console.log(`landing synced: ${body.length} chars of markup, ${extra.length} extra icons, ${swapped} glyphs replaced by logos`);
